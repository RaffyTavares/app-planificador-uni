export const icon = (name, cls = '') =>
    `<svg class="ic ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${ICONS[name] || ''}</svg>`;

export function hydrateIcons(root = document) {
    $$('[data-i]', root).forEach(el => {
        if (!el.firstElementChild) el.innerHTML = icon(el.dataset.i);
    });
}

/** Icono según el tipo de archivo. */
export function iconoArchivo(nombre = '', mime = '') {
    const ext = String(nombre).split('.').pop().toLowerCase();
    if (mime.startsWith('image/')) return 'image';
    if (mime.startsWith('video/')) return 'film';
    if (mime.startsWith('audio/')) return 'music';
    if (['zip', 'rar', '7z'].includes(ext)) return 'archive';
    if (['xls', 'xlsx', 'ods', 'csv'].includes(ext)) return 'sheet';
    if (['ppt', 'pptx', 'odp'].includes(ext)) return 'presentation';
    if (['java', 'py', 'js', 'ts', 'html', 'css', 'php', 'c', 'cpp', 'h', 'cs', 'sql', 'json', 'xml', 'ipynb'].includes(ext)) return 'code';
    if (['pdf', 'doc', 'docx', 'odt', 'rtf', 'txt', 'md'].includes(ext)) return 'fileText';
    return 'file';
}
